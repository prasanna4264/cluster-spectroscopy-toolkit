import os
import tempfile
import numpy as np
from clusterspec.marz import write_marz, rebin_matrix, to_grid, read_marz_results
from clusterspec.fitsio import _read_builtin, write_spectrum
from clusterspec.clean import clean_spectrum, outlier_mask, window_mask


def test_rebin_conserves_flux():
    w1 = 4500 + np.arange(2000.0)
    w2 = 4500 + 2 * np.arange(1000.0)
    f = np.random.default_rng(0).normal(10, 1, w1.size)
    fo, vo = to_grid(w1, f, np.ones_like(f), w2)
    ok = np.isfinite(fo)
    assert abs(np.nansum(fo) - f[1:-1].sum()) / f.sum() < 2e-3
    assert np.allclose(vo[ok][5:-5], 1.5)                    # 0.25 + 1 + 0.25
    W = rebin_matrix(w1, w2)
    assert W.shape == (1000, 2000)


def test_marz_file_roundtrip():
    d = tempfile.mkdtemp()
    p = os.path.join(d, 'm.fits')
    F = np.random.default_rng(1).normal(0, 1, (3, 50))
    F[0, 5] = np.nan
    write_marz(p, 4500, 2, F, np.ones_like(F), ['a', 'b', 'c'], ra=[1, 2, 3], dec=[0, 0, 0])
    H = _read_builtin(p)
    assert [h.get('EXTNAME') for h, _ in H] == ['INTENSITY', 'VARIANCE', 'FIBRES']
    assert H[0][1].shape == (3, 50) and np.isnan(H[0][1][0, 5]) and np.isnan(H[1][1][0, 5])
    assert H[0][0]['CRVAL1'] == 4500.0


def test_spectrum_roundtrip():
    d = tempfile.mkdtemp()
    p = os.path.join(d, 's.fits')
    write_spectrum(p, 4500, 1, np.arange(10.0), np.ones(10), {'OBJECT': "it's"})
    H = _read_builtin(p)
    assert H[0][0]['OBJECT'] == "it's" and np.allclose(H[0][1], np.arange(10))
    assert H[1][0]['EXTNAME'] == 'ERR'


def test_read_marz_results():
    txt = ("# Results generated by Marz\n"
           "#ID  ,  Name      ,  RA      ,  DEC     ,  Mag,  Type,  AutoTID,  AutoTN   ,  AutoZ   ,"
           "  AutoXCor,  FinTID,  FinTN    ,  FinZ    ,  QOP,  Comment\n"
           " 0001,  blind_0001,  0.0, 0.0,  ,  ,  11 ,  Early ,  0.45100 ,  5.1 ,  11 ,  Early ,"
           "  0.45120 ,  4  ,  \n")
    p = os.path.join(tempfile.mkdtemp(), 'r.mz')
    open(p, 'w').write(txt)
    r = read_marz_results(p)
    assert r.name[0] == 'blind_0001' and r.qop[0] == 4 and abs(r.z[0] - 0.4512) < 1e-9


def test_cleaning():
    w = 4500 + 2 * np.arange(2500.0)
    rng = np.random.default_rng(2)
    f = 10 + rng.normal(0, 1, w.size)
    e = np.ones_like(f)
    line = np.argmin(np.abs(w - 6000))
    f[line - 3:line + 4] += 15 * np.exp(-0.5 * (np.arange(-3, 4) / 1.5) ** 2)   # resolved line
    f[300] += 40                                                                # cosmic ray
    f[900] -= 30                                                                # bad dip
    fc, ec, m = clean_spectrum(w, f, e)
    assert m[300] and m[900] and not m[line] and window_mask(w)[np.argmin(np.abs(w - 7600))]
    assert np.isnan(fc[m]).all()
